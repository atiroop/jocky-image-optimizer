<?php
/**
 * Real local JPEG and PNG encoder integration checks.
 *
 * @package Jocky\ImageOptimizer\Tests
 */

declare(strict_types=1);

require dirname( __DIR__ ) . '/vendor/autoload.php';

use Jocky\ImageOptimizer\Optimization\EncoderRegistry;
use Jocky\ImageOptimizer\Optimization\AvifEncoder;
use Jocky\ImageOptimizer\Optimization\CwebpEncoder;
use Jocky\ImageOptimizer\Optimization\EncoderExecution;
use Jocky\ImageOptimizer\Optimization\EncoderInterface;
use Jocky\ImageOptimizer\Optimization\ImageValidator;
use Jocky\ImageOptimizer\Optimization\JpegtranEncoder;
use Jocky\ImageOptimizer\Optimization\MozJpegEncoder;
use Jocky\ImageOptimizer\Optimization\OptimizationManager;
use Jocky\ImageOptimizer\Optimization\OptimizationRequest;
use Jocky\ImageOptimizer\Optimization\OxipngEncoder;
use Jocky\ImageOptimizer\Optimization\PathGuard;
use Jocky\ImageOptimizer\Optimization\PngquantEncoder;
use Jocky\ImageOptimizer\Optimization\SafeFileReplacer;
use Jocky\ImageOptimizer\Optimization\TemporaryFileManager;
use Jocky\ImageOptimizer\System\BinaryLocator;
use Jocky\ImageOptimizer\System\ProcessRunner;

/** Test-only adapter that deliberately returns corrupt bytes for validation tests. */
final class InvalidOutputEncoder implements EncoderInterface {
	public function id(): string { return 'invalid-output-test'; }
	public function supported_mime_types(): array { return array( 'image/png' ); }
	public function supported_modes(): array { return array( OptimizationRequest::MODE_LOSSLESS ); }
	public function is_available(): bool { return true; }
	public function optimize( string $source_path, string $temporary_output_path, OptimizationRequest $request ): EncoderExecution {
		file_put_contents( $temporary_output_path, "\x89PNG\r\n\x1a\ncorrupt" );
		return new EncoderExecution( EncoderExecution::COMPLETE );
	}
}

/** Test-only adapter that returns a truncated WebP container. */
final class InvalidWebpOutputEncoder implements EncoderInterface {
	public function id(): string { return 'cwebp'; }
	public function supported_mime_types(): array { return array( 'image/png' ); }
	public function supported_modes(): array { return array( OptimizationRequest::MODE_LOSSY ); }
	public function is_available(): bool { return true; }
	public function optimize( string $source_path, string $temporary_output_path, OptimizationRequest $request ): EncoderExecution {
		file_put_contents( $temporary_output_path, "RIFF\x04\0\0\0WEBP" );
		return new EncoderExecution( EncoderExecution::COMPLETE );
	}
}

$assert = static function ( bool $condition, string $message ): void {
	if ( ! $condition ) {
		fwrite( STDERR, "FAIL: {$message}\n" );
		exit( 1 );
	}
	echo "PASS: {$message}\n";
};

$root = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'jio-encoder-' . bin2hex( random_bytes( 8 ) );
if ( ! mkdir( $root, 0700 ) ) {
	fwrite( STDERR, "Unable to create isolated encoder test directory.\n" );
	exit( 1 );
}
$runner   = new ProcessRunner();
$binaries = new BinaryLocator();
$registry = new EncoderRegistry(
	array(
		new MozJpegEncoder( $binaries, $runner ),
		new JpegtranEncoder( $binaries, $runner ),
		new PngquantEncoder( $binaries, $runner ),
		new OxipngEncoder( $binaries, $runner ),
		new CwebpEncoder( $binaries, $runner ),
		new AvifEncoder( $binaries, $runner ),
	)
);
$manager = new OptimizationManager( new PathGuard( array( $root ) ), new ImageValidator(), $registry, new TemporaryFileManager(), new SafeFileReplacer() );
$validator = new ImageValidator();

try {
	foreach ( array( 'cjpeg', 'djpeg', 'jpegtran', 'pngquant', 'oxipng', 'cwebp', 'avifenc', 'dwebp', 'avifdec' ) as $binary_id ) {
		$assert( null !== $binaries->locate( $binary_id ), sprintf( 'required real encoder %s is installed', $binary_id ) );
	}
	$ppm = $root . DIRECTORY_SEPARATOR . 'fixture.ppm';
	$ppm_file = fopen( $ppm, 'wb' );
	fwrite( $ppm_file, "P6\n256 256\n255\n" );
	for ( $y = 0; $y < 256; ++$y ) {
		for ( $x = 0; $x < 256; ++$x ) {
			fwrite( $ppm_file, chr( ( $x * 17 + $y * 3 ) % 256 ) . chr( ( $y * 19 + $x * 5 ) % 256 ) . chr( ( $x * $y ) % 256 ) );
		}
	}
	fclose( $ppm_file );
	$jpeg_source = $root . DIRECTORY_SEPARATOR . 'source.jpg';
	$cjpeg = $binaries->locate( 'cjpeg' );
	$assert( null !== $cjpeg, 'MozJPEG cjpeg executable is installed' );
	$jpeg_generation = $runner->run( $cjpeg, array( '-quality', '98', '-outfile', $jpeg_source, $ppm ), 30 );
	$assert( 0 === $jpeg_generation->exit_code, 'deterministic JPEG fixture generated by the installed MozJPEG encoder' );
	$jpeg_hash = hash_file( 'sha256', $jpeg_source );
	$jpeg_output = $root . DIRECTORY_SEPARATOR . 'optimized.jpg';
	$jpeg_result = $manager->optimize( new OptimizationRequest( $jpeg_source, $jpeg_output, 'mozjpeg', OptimizationRequest::MODE_LOSSY, 75, 60, false ) );
	$assert( 'optimized' === $jpeg_result->status && $jpeg_result->output_bytes < $jpeg_result->input_bytes, 'MozJPEG decodes then re-encodes JPEG to a smaller valid output' );
	$assert( $jpeg_hash === hash_file( 'sha256', $jpeg_source ), 'successful JPEG optimization preserves source bytes' );
	$assert( 'image/jpeg' === $validator->inspect( $jpeg_output, new OptimizationRequest( $jpeg_output, $root . DIRECTORY_SEPARATOR . 'unused.jpg', 'jpegtran', OptimizationRequest::MODE_LOSSLESS ) )->mime, 'optimized JPEG passes output structure validation' );
	$jpeg_lossless_output = $root . DIRECTORY_SEPARATOR . 'lossless.jpg';
	$jpeg_lossless_result = $manager->optimize( new OptimizationRequest( $jpeg_source, $jpeg_lossless_output, 'jpegtran', OptimizationRequest::MODE_LOSSLESS ) );
	$assert( in_array( $jpeg_lossless_result->status, array( 'optimized', 'skipped' ), true ) && null !== $jpeg_lossless_result->output_bytes, 'jpegtran runs and its output is validated and measured' );
	$assert( $jpeg_hash === hash_file( 'sha256', $jpeg_source ), 'jpegtran preserves the source bytes' );

	$png = $root . DIRECTORY_SEPARATOR . 'source.png';
	$png_handle = fopen( $png, 'wb' );
	$chunk = static function ( string $type, string $data ): string {
		return pack( 'N', strlen( $data ) ) . $type . $data . pack( 'H*', hash( 'crc32b', $type . $data ) );
	};
	fwrite( $png_handle, "\x89PNG\r\n\x1a\n" );
	fwrite( $png_handle, $chunk( 'IHDR', pack( 'NNCCCCC', 256, 256, 8, 6, 0, 0, 0 ) ) );
	$scanlines = '';
	for ( $y = 0; $y < 256; ++$y ) {
		$scanlines .= "\0";
		for ( $x = 0; $x < 256; ++$x ) {
			$palette = ( ( intdiv( $x, 16 ) + intdiv( $y, 16 ) ) % 4 );
			$rgba = array( array( 255, 0, 0 ), array( 0, 255, 0 ), array( 0, 0, 255 ), array( 255, 255, 0 ) )[ $palette ];
			$alpha = 0 === $x % 7 ? 0 : 255;
			$scanlines .= chr( $rgba[0] ) . chr( $rgba[1] ) . chr( $rgba[2] ) . chr( $alpha );
		}
	}
	fwrite( $png_handle, $chunk( 'IDAT', gzcompress( $scanlines, 0 ) ) );
	fwrite( $png_handle, $chunk( 'IEND', '' ) );
	fclose( $png_handle );
	$png_hash = hash_file( 'sha256', $png );
	$png_info = $validator->inspect( $png, new OptimizationRequest( $png, $root . DIRECTORY_SEPARATOR . 'temp.png', 'oxipng', OptimizationRequest::MODE_LOSSLESS ) );
	$assert( 'image/png' === $png_info->mime && 256 === $png_info->width, 'generated transparent PNG passes CRC and structure validation' );
	$png_lossless = $root . DIRECTORY_SEPARATOR . 'lossless.png';
	$oxipng_result = $manager->optimize( new OptimizationRequest( $png, $png_lossless, 'oxipng', OptimizationRequest::MODE_LOSSLESS ) );
	$assert( 'optimized' === $oxipng_result->status && $oxipng_result->output_bytes < $oxipng_result->input_bytes, 'oxipng produces a smaller valid PNG' );
	$assert( $png_hash === hash_file( 'sha256', $png ), 'successful lossless PNG optimization preserves source bytes' );
	$png_lossy = $root . DIRECTORY_SEPARATOR . 'lossy.png';
	$pngquant_result = $manager->optimize( new OptimizationRequest( $png, $png_lossy, 'pngquant', OptimizationRequest::MODE_LOSSY, 90, 70, false ) );
	$assert( 'optimized' === $pngquant_result->status && $pngquant_result->output_bytes < $pngquant_result->input_bytes, 'pngquant produces a smaller valid PNG' );
	$assert( $validator->inspect( $png_lossy, new OptimizationRequest( $png_lossy, $root . DIRECTORY_SEPARATOR . 'unused.png', 'oxipng', OptimizationRequest::MODE_LOSSLESS ) )->mime === 'image/png', 'pngquant output passes structure and CRC checks' );
	$gd_png = imagecreatefrompng( $png_lossy );
	$alpha_pixel = imagecolorsforindex( $gd_png, imagecolorat( $gd_png, 0, 0 ) );
	imagedestroy( $gd_png );
	$assert( 127 === $alpha_pixel['alpha'], 'pngquant output retains the fully transparent sample pixel' );

	$convert = static function ( string $source, string $encoder, string $format, string $mode, bool $alpha_expected = false ) use ( $manager, $root, $validator, $assert, $runner, $binaries ): void {
		$extension = 'image/webp' === $format ? 'webp' : 'avif';
		$output = $root . DIRECTORY_SEPARATOR . basename( $source ) . '.' . $extension . '.' . $mode;
		$before = hash_file( 'sha256', $source );
		$request = new OptimizationRequest( $source, $output, $encoder, $mode, 78, 60, false, 52428800, 40000000, 180000, $format, true, 6 );
		$result = $manager->optimize( $request );
		if ( 'failed' === $result->status && 'invalid_image' === $result->error_category ) {
			$debug_output = $root . DIRECTORY_SEPARATOR . 'validator-debug.' . $extension;
			$binary = $binaries->locate( $encoder );
			$runner->run( (string) $binary, array( '-quiet', '-m', '4', '-q', '78', $source, '-o', $debug_output ), 30 );
			try {
				$validator->inspect( $debug_output, $request );
			} catch ( Throwable $exception ) {
				fwrite( STDERR, 'Validator detail: ' . $exception->getMessage() . "\n" );
			}
		}
		$assert( 'optimized' === $result->status && null !== $result->output_bytes && is_file( $output ), sprintf( '%s to %s conversion produces a measured output (status: %s; error: %s)', mime_content_type( $source ), $format, $result->status, $result->error_category ?? 'none' ) );
		$assert( $before === hash_file( 'sha256', $source ), 'source bytes remain unchanged after conversion' );
		$info = $validator->inspect( $output, $request );
		$assert( $format === $info->mime && $info->width === 256 && $info->height === 256, sprintf( '%s output structure and dimensions validate', $format ) );
		$decoder = $binaries->locate( 'image/webp' === $format ? 'dwebp' : 'avifdec' );
		$decoded = $output . '.decoded.png';
		$decode_args = 'image/webp' === $format ? array( $output, '-o', $decoded ) : array( $output, $decoded );
		$decode_result = $runner->run( (string) $decoder, $decode_args, 30 );
		$assert( 0 === $decode_result->exit_code && is_file( $decoded ), sprintf( 'independent %s decoder accepts output', $format ) );
		$decoded_image = imagecreatefrompng( $decoded );
		$assert( false !== $decoded_image && imagesx( $decoded_image ) === 256 && imagesy( $decoded_image ) === 256, 'independent decoder confirms output dimensions' );
		if ( false !== $decoded_image && $alpha_expected ) {
			$pixel = imagecolorsforindex( $decoded_image, imagecolorat( $decoded_image, 0, 0 ) );
			$assert( 127 === $pixel['alpha'], sprintf( 'transparent PNG alpha survives %s conversion and independent decode', $format ) );
		}
		if ( false !== $decoded_image ) { imagedestroy( $decoded_image ); }
		$assert( $result->input_bytes === filesize( $source ) && $result->output_bytes === filesize( $output ) && is_float( $result->duration_milliseconds ), 'conversion reports actual byte counts and elapsed time' );
		printf( "BENCHMARK %s -> %s: %d to %d bytes, %.1f ms\n", basename( $source ), $format, $result->input_bytes, $result->output_bytes, $result->duration_milliseconds );
	};
	$convert( $jpeg_source, 'cwebp', OptimizationRequest::OUTPUT_WEBP, OptimizationRequest::MODE_LOSSY );
	$convert( $jpeg_source, 'avifenc', OptimizationRequest::OUTPUT_AVIF, OptimizationRequest::MODE_LOSSY );
	$convert( $png, 'cwebp', OptimizationRequest::OUTPUT_WEBP, OptimizationRequest::MODE_LOSSY, true );
	$convert( $png, 'avifenc', OptimizationRequest::OUTPUT_AVIF, OptimizationRequest::MODE_LOSSY, true );
	$convert( $png, 'cwebp', OptimizationRequest::OUTPUT_WEBP, OptimizationRequest::MODE_LOSSLESS, true );
	$convert( $png, 'avifenc', OptimizationRequest::OUTPUT_AVIF, OptimizationRequest::MODE_LOSSLESS, true );

	$corrupt_jpeg = $root . DIRECTORY_SEPARATOR . 'corrupt.jpg';
	file_put_contents( $corrupt_jpeg, "\xff\xd8broken\xff\xd9" );
	$corrupt_hash = hash_file( 'sha256', $corrupt_jpeg );
	$corrupt_result = $manager->optimize( new OptimizationRequest( $corrupt_jpeg, $root . DIRECTORY_SEPARATOR . 'corrupt-out.jpg', 'mozjpeg', OptimizationRequest::MODE_LOSSY, 75, 60, false ) );
	$assert( 'failed' === $corrupt_result->status && $corrupt_hash === hash_file( 'sha256', $corrupt_jpeg ), 'corrupt JPEG is rejected without changing source' );
	$corrupt_png = $root . DIRECTORY_SEPARATOR . 'corrupt.png';
	file_put_contents( $corrupt_png, substr_replace( file_get_contents( $png ), "\0", 41, 1 ) );
	$corrupt_png_hash = hash_file( 'sha256', $corrupt_png );
	$corrupt_png_result = $manager->optimize( new OptimizationRequest( $corrupt_png, $root . DIRECTORY_SEPARATOR . 'corrupt-out.png', 'oxipng', OptimizationRequest::MODE_LOSSLESS ) );
	$assert( 'failed' === $corrupt_png_result->status && 'png_crc_mismatch' === $corrupt_png_result->error_category && $corrupt_png_hash === hash_file( 'sha256', $corrupt_png ), 'corrupted PNG CRC is rejected without changing source' );

	$existing = $root . DIRECTORY_SEPARATOR . 'existing.png';
	file_put_contents( $existing, 'keep-existing' );
	$no_clobber = $manager->optimize( new OptimizationRequest( $png, $existing, 'oxipng', OptimizationRequest::MODE_LOSSLESS ) );
	$assert( 'destination_exists' === $no_clobber->error_category && 'keep-existing' === file_get_contents( $existing ), 'existing destination is not overwritten' );
	$invalid_registry = new EncoderRegistry( array( new InvalidOutputEncoder() ) );
	$invalid_manager = new OptimizationManager( new PathGuard( array( $root ) ), $validator, $invalid_registry, new TemporaryFileManager(), new SafeFileReplacer() );
	$invalid_destination = $root . DIRECTORY_SEPARATOR . 'invalid-output.png';
	$invalid_result = $invalid_manager->optimize( new OptimizationRequest( $png, $invalid_destination, 'invalid-output-test', OptimizationRequest::MODE_LOSSLESS ) );
	$assert( 'failed' === $invalid_result->status && 'invalid_image' === $invalid_result->error_category, 'corrupt encoder output is rejected before promotion' );
	$assert( ! file_exists( $invalid_destination ) && $png_hash === hash_file( 'sha256', $png ), 'output validation failure retains source and leaves destination absent' );
	$invalid_webp_registry = new EncoderRegistry( array( new InvalidWebpOutputEncoder() ) );
	$invalid_webp_manager = new OptimizationManager( new PathGuard( array( $root ) ), $validator, $invalid_webp_registry, new TemporaryFileManager(), new SafeFileReplacer() );
	$invalid_webp_destination = $root . DIRECTORY_SEPARATOR . 'invalid-output.webp';
	$invalid_webp_result = $invalid_webp_manager->optimize( new OptimizationRequest( $png, $invalid_webp_destination, 'cwebp', OptimizationRequest::MODE_LOSSY, 80, 65, false, 52428800, 40000000, 120000, OptimizationRequest::OUTPUT_WEBP ) );
	$assert( 'failed' === $invalid_webp_result->status && 'invalid_image' === $invalid_webp_result->error_category, 'truncated WebP encoder output is rejected' );
	$assert( ! file_exists( $invalid_webp_destination ) && $png_hash === hash_file( 'sha256', $png ), 'invalid WebP output leaves source intact and destination absent' );
	$djpeg_path = $binaries->locate( 'djpeg' );
	$assert( null !== $djpeg_path, 'MozJPEG djpeg executable is installed' );
	$failing_registry = new EncoderRegistry( array( new MozJpegEncoder( new BinaryLocator( array( 'djpeg' => $djpeg_path, 'cjpeg' => PHP_BINARY ) ), $runner ) ) );
	$failing_manager = new OptimizationManager( new PathGuard( array( $root ) ), $validator, $failing_registry, new TemporaryFileManager(), new SafeFileReplacer() );
	$failure_output = $root . DIRECTORY_SEPARATOR . 'encoder-failure.jpg';
	$failed_hash = hash_file( 'sha256', $jpeg_source );
	$failed_result = $failing_manager->optimize( new OptimizationRequest( $jpeg_source, $failure_output, 'mozjpeg', OptimizationRequest::MODE_LOSSY, 75, 60, false ) );
	$assert( 'failed' === $failed_result->status && 'encoder_failed' === $failed_result->error_category, 'non-zero encoder exit is reported as an encoder failure' );
	$assert( ! file_exists( $failure_output ) && $failed_hash === hash_file( 'sha256', $jpeg_source ), 'failed encoder leaves source intact and does not create a destination' );
	try {
		$runner->run( PHP_BINARY, array( '-r', 'usleep(3000000);' ), 1 );
		$assert( false, 'process runner timeout is enforced' );
	} catch ( \Jocky\ImageOptimizer\Optimization\OptimizationException $exception ) {
		$assert( 'encoder_timeout' === $exception->category, 'process runner timeout is enforced' );
	}
	if ( function_exists( 'symlink' ) && @symlink( $png, $root . DIRECTORY_SEPARATOR . 'linked.png' ) ) {
		$link_result = $manager->optimize( new OptimizationRequest( $root . DIRECTORY_SEPARATOR . 'linked.png', $root . DIRECTORY_SEPARATOR . 'linked-output.png', 'oxipng', OptimizationRequest::MODE_LOSSLESS ) );
		$assert( 'invalid_source_path' === $link_result->error_category, 'symlink source is rejected' );
		unlink( $root . DIRECTORY_SEPARATOR . 'linked.png' );
	}

	$pngquant_path = $binaries->locate( 'pngquant' );
	$missing_locator = new BinaryLocator( array( 'oxipng' => $root . DIRECTORY_SEPARATOR . 'missing-oxipng' ) );
	$missing_registry = new EncoderRegistry( array( new OxipngEncoder( $missing_locator, $runner ) ) );
	$missing_manager = new OptimizationManager( new PathGuard( array( $root ) ), $validator, $missing_registry, new TemporaryFileManager(), new SafeFileReplacer() );
	$unavailable = $missing_manager->optimize( new OptimizationRequest( $png, $root . DIRECTORY_SEPARATOR . 'unavailable.png', 'oxipng', OptimizationRequest::MODE_LOSSLESS ) );
	$assert( 'unavailable' === $unavailable->status, 'missing encoder returns the unavailable status' );
	$assert( null !== $pngquant_path, 'pngquant is available for failure and timeout coverage' );

	$leftovers = glob( $root . DIRECTORY_SEPARATOR . '.jio-*' );
	$assert( array() === $leftovers, 'engine temporary files are cleaned after completed and failed operations' );
} finally {
	foreach ( glob( $root . DIRECTORY_SEPARATOR . '*' ) ?: array() as $path ) {
		if ( is_file( $path ) && ! is_link( $path ) ) {
			unlink( $path );
		}
	}
	rmdir( $root );
}
